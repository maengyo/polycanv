"""앱이 가져가는 키.

터미널 패널은 키를 전부 PTY 로 넘긴다 — 그게 터미널이 할 일이다. 그래서 앱 단축키는
그냥 두면 영영 닿지 않는다(실측: `ctrl+n` 이 셸로 흘러가 도구 목록이 안 떴다).

**그렇다고 `ctrl+n` 같은 키를 앱이 가져가면 안 된다.** 전부 readline 이 쓰는 키다 —
`ctrl+w` 단어 삭제, `ctrl+n` 히스토리, `ctrl+t` 글자 바꾸기. 안에서 도는 CLI 가
멀쩡히 쓰던 조작을 뺏는 셈이고, 그건 터미널로서 못 쓸 물건이 된다는 뜻이다.

그래서 **접두키 하나만 가져간다.** tmux 와 같은 방식이고 같은 키다 — 이 도구를 쓸
사람들은 이미 이 습관을 갖고 있다.
"""

#: 이 키 하나만 앱이 가져간다. 나머지는 전부 안쪽 프로그램의 것이다.
PREFIX = "ctrl+b"

#: 접두키를 그대로 안쪽에 보내야 할 때 쓸 바이트 (접두키를 두 번 누르면).
PREFIX_BYTE = "\x02"

#: 접두키 다음에 오는 글자 → 앱 동작.
COMMANDS = {
    "n": "launch",
    "t": "new_shell",
    "w": "close_focused",
    "d": "toggle_theme",
    "q": "quit",
}

#: 아래에 늘 띄워 두는 안내. 접두키는 눌러 보기 전에는 있는 줄 모른다.
HINT = "ctrl+b  →  n 도구  ·  t 셸  ·  w 닫기  ·  d 테마  ·  q 종료"
